def build(padnet, comps):
    pcbnew.KIID.SeedGenerator(20260925)       # deterministic KIIDs -> deterministic save order (lesson 8)
    tmp = G.PCB + ".tmp.kicad_pcb"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(skeleton_text())
    board = pcbnew.LoadBoard(tmp)
    B = Builder(board, padnet)
    for nm in sorted(set(padnet.values())):
        B.net(nm)

    # --------------------------------------------------------------- outline
    B.shape_prims(outline_prims(), pcbnew.Edge_Cuts, 0.05)

    # --------------------------------------------------------------- holes (board-only NPTH footprints)
    for i, (name, d, X, Z, purpose) in enumerate(P.HOLES):
        fp = B.place(f"H{i + 1}", G.FP_NPTH[d], P.to_k(X, Z), 0, sym=False, value=f"{name} {purpose}")
        fp.SetBoardOnly(True)

    # --------------------------------------------------------------- parts (all on F = the underside)
    for colour in ("warm", "cool"):
        for ref, X in zip(P.LED[colour]["refs"], P.LED[colour]["x"]):
            B.place(ref, G.FP_LED, P.to_k(X, P.LED["z"]), 180, comps[ref], comps[ref]["value"])
    for ref, (X, Z, rot) in P.PARTS_E.items():
        B.place(ref, G.FP_R, P.to_k(X, Z), rot, comps[ref], comps[ref]["value"])
    for ref in P.HEADERS:
        B.place(ref, G.FP_HDR[ref], P.to_k(*P.header_centre(ref)), 0, comps[ref], comps[ref]["value"])

    # --------------------------------------------------------------- routing
    W, C = P.LED["warm"]["refs"], P.LED["cool"]["refs"]
    wr, wb = R["w_row"], R["w_bus"]
    for refs, y in ((W, R["y_warm_link"]), (C, R["y_cool_link"])):
        for a_ref, b_ref in zip(refs[:-1], refs[1:]):
            k = B.pad_xy(a_ref, "1")
            a = B.pad_xy(b_ref, "2")
            B.route(B.pad_net(a_ref, "1"), FC, wr, [k, (k[0], y), (a[0], y), a], 0.3)
    # anode bridge between D1 and D6 (above the row) and the drop to the LED_SW via
    sw = B.pad_net("J1", "5")
    a1, a6 = B.pad_xy(W[0], "2"), B.pad_xy(C[0], "2")
    B.route(sw, FC, wr, [a1, (a1[0], R["y_cool_link"]), (a6[0], R["y_cool_link"]), a6], 0.3)
    va = (a1[0], R["y_sw_via"])
    B.route(sw, FC, wb, [a1, va])
    B.via(sw, va)
    # returns: last cathodes -> R1 / R2 pad 1 (F.Cu)
    for last, rref, y in ((W[-1], "R1", R["y_w_ret"]), (C[-1], "R2", R["y_c_ret"])):
        k = B.pad_xy(last, "1")
        rp = B.pad_xy(rref, "1")
        B.route(B.pad_net(last, "1"), FC, wb, [k, (k[0], y), (rp[0], y), rp], 0.8)
    # W-: R1 pad 2 -> J1 "6" from below (passes J6-4 at > 1.0)
    p = B.pad_xy("R1", "2")
    j6 = B.pad_xy("J1", "6")
    B.route(B.pad_net("R1", "2"), FC, wb, [p, (p[0], R["y_wminus"]), (j6[0], R["y_wminus"]), j6], 0.8)
    # C-: R2 pad 2 -> J2 "11"
    p = B.pad_xy("R2", "2")
    j11 = B.pad_xy("J2", "11")
    B.route(B.pad_net("R2", "2"), FC, wb, [p, j11])
    # LED_SW bus on B.Cu: D1 via -> x_sw_down -> 45 deg into J1 "5" between J2 "11" and J6-4
    j5 = B.pad_xy("J1", "5")
    xs, yt = R["x_sw_down"], R["y_sw_turn"]
    if abs((j5[0] - xs) - (j5[1] - yt)) > 1e-3:
        raise SystemExit("LED_SW bus: the last leg into J1-5 is not 45 deg")
    B.route(sw, BC, wb, [va, (xs, va[1]), (xs, yt), j5], 0.5)

    # --------------------------------------------------------------- documentation layers
    k = P.to_k
    U1, U2, U3 = pcbnew.User_1, pcbnew.User_2, pcbnew.User_3
    for name, x0, x1, z0, z1 in P.KEEPOUTS:
        B.rect(k(x0, z1), k(x1, z0), U1, 0.05)
    B.text("Outlined = no parts (DESIGN-SPEC-revB keep-outs); traces allowed", k(0, 13.0), U1, 0.8, justify="left")
    for (x0, x1, z0, z1) in (P.R_ZONE, P.J6_OPENING):
        B.rect(k(x0, z1), k(x1, z0), U2, 0.05)
    B.text("J6 opening / R zone", k(50.0, 1.2), U2, 0.5)
    for pin, (X, Z) in P.J6["pins"].items():
        B.circle(k(X, Z), 0.5, U3, 0.05)
        B.text(f"J6-{pin} {P.J6['net'][pin]}", k(X, Z - 1.1), U3, 0.35)
    for X, Z, _ in P.PLUG["forbidden"]:
        B.circle(k(X, Z), P.PLUG["forbid_r"], U3, 0.05)

    # --------------------------------------------------------------- silkscreen, B side (the top, under the lid)
    SB = pcbnew.B_SilkS
    B.text("SILKSCREEN LIGHT ATTACHMENT", (124.0, 95.0), SB, 1.0, mirror=True)
    B.text(f"rev {P.REVISION}  {P.DATE}", (124.0, 97.0), SB, 1.0, mirror=True)
    ax, ay0, ay1 = 104.0, 98.2, 93.6                    # "SCREEN" arrow toward +Z (= -y_K)
    B.line((ax, ay0), (ax, ay1), SB, 0.2)
    B.line((ax, ay1), (ax - 0.6, ay1 + 1.0), SB, 0.2)
    B.line((ax, ay1), (ax + 0.6, ay1 + 1.0), SB, 0.2)
    B.text("SCREEN", (ax, 99.6), SB, 1.0, mirror=True)
    B.text("5", (j5[0] - 2.1, j5[1] + 0.3), SB, 1.0, mirror=True)
    B.text("6", (j6[0] + 2.1, j6[1]), SB, 1.0, mirror=True)
    B.text("11", (j11[0], j11[1] - 2.0), SB, 1.0, mirror=True)
    # F side: string labels by the first LEDs, one outline around both header bodies
    SF = pcbnew.F_SilkS
    B.text("W", (a1[0] + 1.9, 93.4), SF, 1.0)
    B.text("C", (a6[0], 93.4), SF, 1.0)
    b1, b2 = P.header_body("J1"), P.header_body("J2")
    d = 0.20
    ol = [(b1[0] - d, b1[2] - d), (b1[1] + d, b1[2] - d), (b1[1] + d, b1[3] + d), (b2[1] + d, b1[3] + d),
          (b2[1] + d, b2[3] + d), (b2[0] - d, b2[3] + d)]
    for i in range(len(ol)):
        B.line(k(*ol[i]), k(*ol[(i + 1) % len(ol)]), SF, P.RULES["silk_line_w"])

    # --------------------------------------------------------------- fab notes (outside the board)
    notes = [
        f"SILKSCREEN LIGHT ATTACHMENT rev {P.REVISION} - FAB NOTES (JLCPCB standard 2-layer)",
        "FR-4 1.0 mm, 1 oz, any solder mask colour (black preferred), white silk, LF-HASL or ENIG. No order numbers.",
        "All 12 SMD parts on the F side. J1 (1x2) and J2 (1x1) THT headers are NOT assembled: hand-soldered by the builder.",
        "Header pads are named by the mating J6 pin: 5 LED_SW, 6 W-, 11 C-. No pad or hole at any other J6 position.",
        "2 x 4.80 mm NPTH (housing bosses); every NPTH keeps >= 0.50 of FR-4 to the edge.",
    ]
    for i, s in enumerate(notes):
        B.text(s, (96.0, 110.0 + i * 1.6), pcbnew.Cmts_User, 0.9, 0, justify="left")

    board.SetFileName(G.PCB)
    pcbnew.SaveBoard(G.PCB, board, True)      # skip settings: the .kicad_pro is written by generate.py
    os.remove(tmp)
    for extra in (tmp.replace(".kicad_pcb", ".kicad_pro"), tmp.replace(".kicad_pcb", ".kicad_prl")):
        if os.path.exists(extra):
            os.remove(extra)
    n = uuid_rewrite(G.PCB)
    # KiCad orders footprints by KIID on save; the first save used random KIIDs, so load the rewritten file
    # (now deterministic KIIDs) and save once more to get a stable item order.
    b2 = pcbnew.LoadBoard(G.PCB)
    pcbnew.SaveBoard(G.PCB, b2, True)
    print("board saved; deterministic uuids:", n)
