class Builder:
    def __init__(self, board, padnet):
        self.b = board
        self.padnet = padnet
        self.nets = {}
        self.fps = {}

    def net(self, name):
        if name is None:
            return None
        if name not in self.nets:
            ni = pcbnew.NETINFO_ITEM(self.b, name)
            self.b.Add(ni)
            self.nets[name] = ni
        return self.nets[name]

    def pad_xy(self, ref, num):
        for p in self.fps[ref].Pads():
            if p.GetNumber() == num:
                pos = p.GetPosition()
                return (pcbnew.ToMM(pos.x), pcbnew.ToMM(pos.y))
        raise KeyError((ref, num))

    def pad_net(self, ref, num):
        return self.padnet[(ref, num)]

    def route(self, net, layer, width, pts, radius=0.4):
        radii = [0] + [radius] * (len(pts) - 2) + [0]
        n = self.net(net)
        for p in rounded_path(pts, radii, closed=False):
            if p[0] == "line":
                t = pcbnew.PCB_TRACK(self.b)
                t.SetStart(V(*p[1]))
                t.SetEnd(V(*p[2]))
            else:
                t = pcbnew.PCB_ARC(self.b)
                t.SetStart(V(*p[1]))
                t.SetMid(V(*p[2]))
                t.SetEnd(V(*p[3]))
            t.SetWidth(MM(width))
            t.SetLayer(layer)
            t.SetNet(n)
            self.b.Add(t)

    def via(self, net, at):
        v = pcbnew.PCB_VIA(self.b)
        v.SetPosition(V(*at))
        v.SetViaType(pcbnew.VIATYPE_THROUGH)
        v.SetLayerPair(FC, BC)
        v.SetDrill(MM(P.RULES["via_drill"]))
        try:
            v.SetWidth(MM(P.RULES["via_pad"]))
        except TypeError:
            v.SetWidth(FC, MM(P.RULES["via_pad"]))
        v.SetNet(self.net(net))
        self.b.Add(v)

    def shape_prims(self, prims, layer, width):
        for p in prims:
            s = pcbnew.PCB_SHAPE(self.b)
            if p[0] == "line":
                s.SetShape(pcbnew.SHAPE_T_SEGMENT)
                s.SetStart(V(*p[1]))
                s.SetEnd(V(*p[2]))
            else:
                s.SetShape(pcbnew.SHAPE_T_ARC)
                s.SetArcGeometry(V(*p[1]), V(*p[2]), V(*p[3]))
            s.SetLayer(layer)
            s.SetWidth(MM(width))
            self.b.Add(s)

    def line(self, a, b, layer, width=0.1):
        self.shape_prims([("line", a, b)], layer, width)

    def rect(self, a, b, layer, width=0.1):
        pts = [a, (b[0], a[1]), b, (a[0], b[1])]
        for i in range(4):
            self.line(pts[i], pts[(i + 1) % 4], layer, width)

    def circle(self, c, r, layer, width=0.1):
        s = pcbnew.PCB_SHAPE(self.b)
        s.SetShape(pcbnew.SHAPE_T_CIRCLE)
        s.SetCenter(V(*c))
        s.SetEnd(V(c[0] + r, c[1]))
        s.SetLayer(layer)
        s.SetWidth(MM(width))
        self.b.Add(s)

    def text(self, s, at, layer, h=1.0, angle=0, w=None, justify=None, mirror=False):
        t = pcbnew.PCB_TEXT(self.b)
        t.SetText(s)
        t.SetPosition(V(*at))
        t.SetLayer(layer)
        t.SetTextSize(pcbnew.VECTOR2I(MM(h), MM(h)))
        t.SetTextThickness(MM(w if w is not None else max(0.15, h * 0.15)))
        t.SetTextAngleDegrees(angle)
        if justify == "left":
            t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT)
        if mirror:
            t.SetMirrored(True)
        self.b.Add(t)

    def place(self, ref, fpname, at, rot, comp=None, value=None, sym=True):
        fp = pcbnew.FootprintLoad(G.PRETTY, fpname)
        if fp is None:
            raise RuntimeError("footprint not found: " + fpname)
        fp.SetReference(ref)
        fp.SetValue(value or fpname)
        fp.SetFPIDAsString(f"{G.LIBNAME}:{fpname}")
        fp.SetPosition(V(*at))
        fp.SetOrientationDegrees(rot)
        if sym:
            fp.SetPath(pcbnew.KIID_PATH("/" + uid("sym", ref)))
            fp.SetSheetname("/")
            fp.SetSheetfile(G.NAME + ".kicad_sch")
        for k, v in sorted((comp or {}).get("fields", {}).items()):
            if k in ("Footprint", "Reference", "Value"):
                continue
            fp.SetField(k, v)
        if comp is not None:
            fp.SetDNP(bool(comp.get("dnp")))
        for fld in fp.GetFields():
            if fld.GetName() != "Reference":
                fld.SetVisible(False)
        fp.Reference().SetVisible(False)
        for pad in fp.Pads():
            nm = self.padnet.get((ref, pad.GetNumber()))
            if nm:
                pad.SetNet(self.net(nm))
        self.b.Add(fp)
        self.fps[ref] = fp
        return fp


# =====================================================================================
def outline_points():
    """Board outline in K: rounded rectangle, all corners R (DESIGN-SPEC-revB, PCB)."""
    o = P.OUTLINE
    k = P.to_k
    pts = [k(o["x0"], o["z1"]), k(o["x1"], o["z1"]), k(o["x1"], o["z0"]), k(o["x0"], o["z0"])]
    return pts, [o["r"]] * 4


def outline_prims():
    pts, radii = outline_points()
    return rounded_path(pts, radii, closed=True)


def uuid_rewrite(path):
    """Replace every KIID with a deterministic hash of its order in the file (lesson 8)."""
    txt = open(path, encoding="utf-8").read()
    cnt = [0]

    def rep(m):
        cnt[0] += 1
        return f'(uuid "{uid("pcb", cnt[0])}")'
    txt = re.sub(r'\(uuid "[0-9a-fA-F-]{36}"\)', rep, txt)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(txt)
    return cnt[0]


